const test=require('node:test'),assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../pack/earnings.js'),'utf8'),helpers=source.slice(source.indexOf('function cfEarningWorkerBreakdown('),source.indexOf('async function cfShowEarnings('));
const rows=[{id:'a',work_date:'2026-10-20',contractor:'Browar',employee_name:' Tata ',employee_amount:100,employee_paid:false},{id:'b',work_date:'2026-10-21',contractor:'TVM',employee_name:'tata',employee_amount:20,employee_paid:true},{id:'c',work_date:'2026-10-22',contractor:'TVM',employee_name:'Melania <test>',employee_amount:200,employee_paid:true},{id:'d',work_date:'2026-10-23',contractor:'Browar',employee_name:null,employee_amount:10,employee_paid:false}];
